import assert from 'node:assert/strict';
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
const directory = await fs.mkdtemp('./.data/asset-style-fixes-');
const bundle = await build({entryPoints:['src/lib/maskHoles.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {restoreEnclosedPixels} = await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const original = new Uint8ClampedArray(5*5*4).fill(255);
const mask = original.slice();
mask[3] = 0;
mask[(2*5+2)*4+3] = 0;
const result = restoreEnclosedPixels(5,5,mask,original);
assert.equal(result.pixels[3],0,'border-connected background remains transparent');
assert.equal(result.pixels[(2*5+2)*4+3],255,'enclosed face/coin hole restored');
assert.equal(mask[(2*5+2)*4+3],0,'input remains immutable');
assert.equal(result.restored,1);
const browser = await chromium.launch({channel:'msedge',headless:true});
try {
 const page = await browser.newPage({viewport:{width:960,height:720}});
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:5174/');
 const card=page.locator('.screen-card').first(); await card.waitFor();
 await card.locator('.screen-preview-frame').last().hover();
 await card.getByRole('button',{name:'编辑资源',exact:true}).click();
 const editor=page.getByRole('dialog',{name:'资源编辑器',exact:true}); await editor.waitFor();
 const source=editor.locator('.asset-source');
 await page.waitForTimeout(200);
 const bounds=await source.boundingBox();
 assert.ok(bounds.y+bounds.height<=720,'source viewport fits small window');
 assert.ok(await source.evaluate(element=>element.scrollHeight>element.clientHeight),'source has independent overflow');
 await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height-20);
 await page.mouse.down();
 await page.mouse.move(bounds.x+bounds.width/2,bounds.y+30,{steps:10});
 await page.mouse.up();
 assert.ok(await source.evaluate(element=>element.scrollTop>30),'pointer drag scrolls source');
 await page.screenshot({path:directory+'/assets-small.png'});
 await editor.getByRole('button',{name:'关闭资源编辑器'}).click();
 await page.getByRole('button',{name:'返回首页',exact:true}).click(); await page.getByRole('button',{name:'我的风格库',exact:true}).click();
 assert.equal(await page.locator('.style-create').count(),0,'manual form absent from library overview');
 await page.getByRole('button',{name:'手动新增风格',exact:true}).click();
 const manual=page.getByRole('main',{name:'手动新增风格',exact:true}); await manual.waitFor();
 await page.screenshot({path:directory+'/style-dialog.png'});
 await manual.getByRole('button',{name:'取消编辑',exact:true}).click();
 await page.getByRole('button',{name:'AI 创建 / 提取画风',exact:true}).click();
 await page.getByRole('dialog',{name:'AI 创建画风',exact:true}).waitFor();
 assert.ok(await page.locator('.style-generator-actions [role=status]').innerText(),'disabled/action state has an explanation');
 await page.screenshot({path:directory+'/ai-status.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS enclosed mask restoration, small-window drag scrolling, separate style dialogs and explicit AI status; '+directory);
} finally {await browser.close();}
