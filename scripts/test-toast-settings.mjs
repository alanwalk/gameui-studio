import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
const directory=await fs.mkdtemp('./.data/toast-settings-');
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:5174/');
 await page.locator('.screen-card').first().waitFor();
 assert.equal(await page.getByRole('button',{name:'竖屏',exact:true}).count(),0);
 assert.equal(await page.getByRole('button',{name:'横屏',exact:true}).count(),0);
 await page.getByLabel('画布宽度').waitFor();
 const before=await page.locator('.project-overview').boundingBox();
 await page.getByRole('button',{name:'项目风格',exact:true}).click();
 await page.keyboard.press('Escape');
 const after=await page.locator('.project-overview').boundingBox();
 assert.deepEqual(after,before,'opening panels must not shift the overview');
 assert.equal(await page.locator('.toast-queue').evaluate(element=>getComputedStyle(element).position),'fixed');
 const card=page.locator('.screen-card').first();
 await card.locator('.screen-preview-frame').last().hover();
 await card.getByRole('button',{name:'编辑资源',exact:true}).click();
 const resources=page.getByRole('dialog',{name:'资源编辑器',exact:true});
 await resources.getByText('素材与导出设置',{exact:true}).click();
 assert.equal(await resources.getByLabel('素材命名模块').count(),1);
 await resources.getByRole('button',{name:'关闭资源编辑器'}).click();
 await page.getByRole('button',{name:'设置',exact:true}).click();
 assert.equal(await page.getByLabel('素材命名模块').count(),0);
 await page.getByRole('button',{name:'返回首页',exact:true}).click(); await page.getByRole('button',{name:'我的风格库',exact:true}).click();
 await page.getByRole('button',{name:'手动新增风格',exact:true}).click();
 const dialog=page.getByRole('main',{name:'手动新增风格',exact:true});
 const input=await dialog.getByLabel('名称',{exact:true}).boundingBox();
 const box=await dialog.locator('.style-details-description').boundingBox();
 assert.ok(input.width>box.width*.8,'form fills dialog width');
 await page.screenshot({path:directory+'/style-form.png'});
 await dialog.getByRole('button',{name:'取消编辑',exact:true}).click();
 assert.deepEqual(errors,[]);
 console.log('PASS resolution controls, fixed toast host/no layout shift, screen-local export UI, full-width style form; '+directory);
} finally {await browser.close();}
