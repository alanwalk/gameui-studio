import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';

const directory=await fs.mkdtemp('./.data/studio-visual-');
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1920,height:940}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:5174/');
  const home=page.getByRole('main',{name:'首页',exact:true});
  await home.locator('.home-project-open').first().waitFor();
  assert.equal(await page.locator('.home-sidebar').evaluate(el=>Math.round(el.getBoundingClientRect().width)),288);
  const background=await page.locator('.app').evaluate(el=>getComputedStyle(el).backgroundColor);
  assert.equal(background,'rgb(9, 9, 9)');
  await page.screenshot({path:directory+'/home.png'});
  const project=home.locator('.home-project-open').filter({has:page.locator('img')}).first();
  await project.click();
  const overview=page.getByRole('main',{name:'项目总览'});
  await overview.waitFor();
  await page.screenshot({path:directory+'/project.png'});
  const card=page.locator('.screen-card').filter({has:page.locator('.screen-preview-frame > img')}).first();
  await card.locator('.screen-preview-frame').first().hover();
  await card.getByRole('button',{name:'编辑布局',exact:true}).click();
  const layout=page.getByRole('dialog',{name:'布局编辑器',exact:true});
  await layout.waitFor();
  const row=layout.locator('.layout-tree-pick').first();
  await row.click();
  assert.equal(await layout.locator('.node-properties').count(),1);
  await row.click();
  assert.equal(await layout.locator('.node-properties').count(),0);
  await page.screenshot({path:directory+'/layout.png'});
  page.once('dialog',dialog=>dialog.accept());
  await layout.getByRole('button',{name:'不保存关闭',exact:true}).click();
  await layout.waitFor({state:'detached'});
  await card.locator('.screen-preview-frame').last().hover();
  await card.getByRole('button',{name:'编辑资源',exact:true}).click();
  const resources=page.getByRole('dialog',{name:'资源编辑器',exact:true});
  await resources.getByAltText('当前素材来源图').waitFor();
  await page.waitForTimeout(250);
  const left=await resources.getByLabel('效果图画布',{exact:true}).boundingBox();
  const right=await resources.locator('.atlas-preview').boundingBox();
  assert.ok(Math.abs(left.width-right.width)<3);
  assert.ok(left.height>500 && right.height>500);
  const addBounds=await resources.getByRole('button',{name:'框选切图',exact:true}).boundingBox();
  assert.ok(addBounds.height<60 && addBounds.width<150,'manual slice action must remain a compact button');
  const autoBounds=await resources.getByRole('button',{name:'一键切图',exact:true}).boundingBox();
  assert.ok(Math.abs(autoBounds.y-addBounds.y)<3,'automatic and manual slice actions align on the same row');
  assert.ok(await resources.getByRole('button',{name:'框选切图',exact:true}).evaluate(el=>{
    const rect=el.getBoundingClientRect();
    return el.contains(document.elementFromPoint(rect.x+rect.width/2,rect.y+rect.height/2));
  }),'manual slice action must not be clipped by either canvas');
  assert.ok(await resources.getByLabel('切图图集画布',{exact:true}).evaluate(el=>getComputedStyle(el).backgroundImage.includes('conic-gradient')));
  await page.screenshot({path:directory+'/assets.png'});
  await resources.getByRole('button',{name:'关闭资源编辑器',exact:true}).click();
  await resources.waitFor({state:'detached'});
  await card.locator('.screen-preview-frame').last().hover();
  await card.getByRole('button',{name:'微调结果',exact:true}).click();
  const refine=page.getByRole('dialog',{name:'微调结果',exact:true});
  await refine.waitFor();
  assert.ok((await refine.boundingBox()).width<=520);
  await page.screenshot({path:directory+'/refine.png'});
  await refine.getByRole('button',{name:'关闭微调结果',exact:true}).click();
  await page.getByRole('button',{name:'返回首页',exact:true}).click();
  await home.waitFor();
  await page.setViewportSize({width:1100,height:800});
  await page.screenshot({path:directory+'/home-1100.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  let analyzed;
  let drawingCalls=0;
  await page.route('**/api/style-generation/analyze', async route=>{
    analyzed=route.request().postDataJSON();
    await route.fulfill({contentType:'application/json',body:JSON.stringify({name:'测试画风',prompt:'明亮的卡通画风',drawingReferences:[]})});
  });
  await page.route('**/api/drawing/tasks',async route=>{drawingCalls++;await route.abort();});
  await home.getByRole('button',{name:'卡通',exact:true}).click();
  await home.getByLabel('画风描述（有参考图时可选）',{exact:true}).fill('森林冒险手游');
  await home.getByRole('button',{name:'开始创作',exact:true}).click();
  await home.getByRole('button',{name:'保存 AI 画风到风格库',exact:true}).waitFor();
  assert.equal(analyzed.description,'卡通风格。森林冒险手游');
  assert.equal(drawingCalls,0);
  assert.deepEqual(errors,[]);
  console.log('PASS home/project/layout/assets/refine visual states, deselection, equal canvases, discard, return home, 1100px viewport; no user data mutations or model calls; '+directory);
} finally { await browser.close(); }
